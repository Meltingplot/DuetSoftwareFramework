/// <summary>
/// Fuzz tests for G-code files: FileInfoParser on mutated sample files, and jobs that are paused at a random line and resumed
/// </summary>
[TestFixture]
public class GCodeFileFuzz
{
    private FakeFirmwareHost? _host;

    [TearDown]
    public async Task TearDown()
    {
        if (_host is not null)
        {
            await _host.DisposeAsync();
            _host = null;
        }
    }

    #region File info
    /// <summary>
    /// Metadata lines as slicers write them, for the keys of the filters in Settings.cs:321-422 and the thumbnail formats of FileInfoParser
    /// </summary>
    private static readonly string[] MetadataTokens =
    [
        "\n; generated by PrusaSlicer 2.6.0\n", "\n;Generated with Cura_SteamEngine 5.0\n", "\n; estimated printing time (normal mode) = 1d 2h 3m 4s\n", "\n;TIME:12345\n",
        "\n; filament used [mm] = 1.5, 2.5\n", "\n;Filament used: 1.2m, 3m\n", "\n; filament used [cm3] = 2.5\n", "\n; layer_height = 0.2\n", "\n;Layer height: 0.2\n",
        "\n;LAYER_COUNT:99\n", "\n;LAYER:5\n", "\n; total layers count = 12\n", "\n; max_layer_z = 10\n", "\n;MAXZ:12.5\n", "\n; Simulated print time: 77\n",
        "\n; thumbnail begin 16x16 100\n; iVBORw0KGgoAAAANSUhEUgAAABAAAAAQ\n; thumbnail end\n", "\n; thumbnail_JPG begin 16x16 8\n; /9j/4AAQ\n; thumbnail_JPG end\n",
        "\n; thumbnail_QOI begin 2x2 12\n; cW9pZgAAAAI=\n; thumbnail_QOI end\n", "\n;Icon:\n", "\nG1 Z0.3 F300\n", "\nG1 Z{1+1}\n", "\nM73 P50 R10\n",
        "\nG10 P0 S200\n", "\nM104 S\n", "\n; thumbnail begin 9999999999x1 -5\n", "\n; thumbnail end\n", "\"", "{", "}", "(", "\r", "\0", "ä", "😀", "\n;", "=", ":", ","
    ];

    /// <summary>
    /// Header and footer of each sample file, which hold the metadata that FileInfoParser reads (Settings.FileInfoReadLimitHeader and Footer)
    /// </summary>
    private static List<byte[]>? _samples;

    private static List<byte[]> Samples
    {
        get
        {
            if (_samples is null)
            {
                _samples = [];
                foreach (string file in Directory.GetFiles(Path.Combine(Directory.GetCurrentDirectory(), "../../../File/GCodes")).Order())
                {
                    byte[] content = System.IO.File.ReadAllBytes(file);
                    _samples.Add((content.Length <= 65536) ? content : [.. content.Take(24576), (byte)'\n', .. content.Skip(content.Length - 32768)]);
                }
            }
            return _samples;
        }
    }

    /// <summary>
    /// Mutation of a sample file
    /// </summary>
    /// <param name="Position">Position as a fraction of the file length in 1/1000000</param>
    /// <param name="Kind">Kind of the mutation</param>
    /// <param name="Value">Token index or random value</param>
    public sealed record Mutation(int Position, int Kind, int Value);

    /// <summary>
    /// Fuzzed file: a sample and the mutations applied to it
    /// </summary>
    public sealed record FileInput(int Sample, IReadOnlyList<Mutation> Mutations);

    private static FileInput GenerateFile(Random random) =>
        new(random.Next(Samples.Count), [.. Enumerable.Range(0, 1 + random.Next(8)).Select(_ => new Mutation(random.Next(1000000), random.Next(6), random.Next()))]);

    private static byte[] Apply(FileInput input)
    {
        List<byte> data = [.. Samples[input.Sample]];
        foreach (Mutation mutation in input.Mutations)
        {
            int position = (int)((long)mutation.Position * data.Count / 1000000);
            switch (mutation.Kind)
            {
                case 0:
                case 1:
                    data.InsertRange(position, Encoding.UTF8.GetBytes(MetadataTokens[mutation.Value % MetadataTokens.Length]));
                    break;
                case 2:
                    if (position < data.Count)
                    {
                        data[position] ^= (byte)(1 << (mutation.Value % 8));
                    }
                    break;
                case 3:
                    data.RemoveRange(position, Math.Min(mutation.Value % 4096, data.Count - position));
                    break;
                case 4:
                    data.InsertRange(position, data.Skip(position).Take(mutation.Value % 2048).ToArray());
                    break;
                default:
                    data.RemoveRange(position, data.Count - position);
                    break;
            }
        }
        return [.. data];
    }

    private static string FormatFile(FileInput input) => $"new FileInput({input.Sample}, [{string.Join(", ", input.Mutations.Select(m => $"new({m.Position}, {m.Kind}, {m.Value})"))}])";

    private static IEnumerable<FileInput> ShrinkFile(FileInput input)
    {
        for (int i = 0; i < input.Mutations.Count; i++)
        {
            yield return input with { Mutations = [.. input.Mutations.Where((_, index) => index != i)] };
        }
    }

    [Test]
    public async Task ParseFileInfo()
    {
        _host = await FakeFirmwareHost.StartAsync();
        FileInfoParser parser = _host.Services.GetRequiredService<FileInfoParser>();
        string path = Path.Combine(_host.BaseDirectory, "gcodes", "fuzz.gcode");

        Fuzzer.Run(GenerateFile, input =>
        {
            byte[] content = Apply(input);
            System.IO.File.WriteAllBytes(path, content);

            // ParseAsync returns the information it could find, malformed thumbnails are skipped (FileInfoParser.cs:720-725)
            Task<GCodeFileInfo> parse = parser.ParseAsync(path, true);
            GCodeFileInfo info;
            try
            {
                if (!parse.Wait(TimeSpan.FromSeconds(10)))
                {
                    throw new FuzzFailure("hang", "ParseAsync did not finish within 10 s");
                }
                info = parse.Result;
            }
            catch (AggregateException ae) when (ae.InnerException is DuetAPI.CodeParserException or DuetAPI.InvalidParameterTypeException)
            {
                // Known finding: a line that the code parser rejects or a Z without a number makes ParseAsync throw (InfoParserErrors.MalformedLine)
                return;
            }
            catch (AggregateException ae)
            {
                throw new FuzzFailure("exception", $"{ae.InnerException!.GetType().Name}: {ae.InnerException.Message}\n{ae.InnerException}");
            }

            if (info.Size != content.Length || info.FileName != "0:/gcodes/fuzz.gcode")
            {
                throw new FuzzFailure("file", $"Size {info.Size} and name {info.FileName} do not describe the file of {content.Length} bytes");
            }
            if (info.NumLayers < 0 || info.Filament.Any(float.IsNaN))
            {
                throw new FuzzFailure("values", $"Invalid values: {info.NumLayers} layers, filament {string.Join(", ", info.Filament)}");
            }

            // The thumbnails can be read back with the offsets that the parser reported (FileInfoParser.ParseFileFragment). The data is copied into
            // the JSON string without escaping, like RRF does (RepRap.cpp:1648 and 1661), so a corrupted thumbnail may give invalid JSON and that is not checked
            foreach (ThumbnailInfo thumbnail in info.Thumbnails)
            {
                if (thumbnail.Offset < 0 || thumbnail.Offset > content.Length)
                {
                    throw new FuzzFailure("thumbnail offset", $"Thumbnail offset {thumbnail.Offset} is outside the file of {content.Length} bytes");
                }
                Task<string> fragment = parser.ParseFileFragment(path, thumbnail.Offset, true).AsTask();
                try
                {
                    if (!fragment.Wait(TimeSpan.FromSeconds(10)))
                    {
                        throw new FuzzFailure("hang", "ParseFileFragment did not finish within 10 s");
                    }
                    if (!fragment.Result.Contains("\"err\":"))
                    {
                        throw new FuzzFailure("thumbnail reply", $"No error code in the reply for the thumbnail at {thumbnail.Offset}");
                    }
                }
                catch (AggregateException ae)
                {
                    throw new FuzzFailure("thumbnail exception", $"{ae.InnerException!.GetType().Name}: {ae.InnerException.Message}");
                }
            }
        }, FormatFile, ShrinkFile, Fuzzer.Scale(150), TimeSpan.FromSeconds(30));
    }
    #endregion

    #region Pause and resume
    /// <summary>
    /// Job of numbered moves and lines that do not reach the firmware, paused at one of the moves and resumed
    /// </summary>
    /// <param name="Lines">Lines of the job</param>
    /// <param name="PauseAt">Number of the move that is held when the job is paused</param>
    /// <param name="PositionMode">0: RRF reports the position after the held move, 1: no position (pause from a code), 2: M26 to a random move before resuming</param>
    /// <param name="RewindTo">Number of the move M26 sets the position to</param>
    public sealed record JobInput(IReadOnlyList<string> Lines, int PauseAt, int PositionMode, int RewindTo);

    private static readonly string[] Fillers = ["; comment", "", "  ", "echo \"x\"", "M400", "(paren comment)", "G4 P0"];

    private static JobInput GenerateJob(Random random)
    {
        List<string> lines = [];
        int numMoves = 2 + random.Next(8);
        for (int i = 0; i < numMoves; i++)
        {
            for (int j = random.Next(3); j > 0; j--)
            {
                lines.Add(Fillers[random.Next(Fillers.Length)]);
            }
            lines.Add($"G1 X{i}");
        }
        return new JobInput(lines, random.Next(numMoves), random.Next(3), random.Next(numMoves));
    }

    private static string FormatJob(JobInput input) =>
        $"new JobInput([{string.Join(", ", input.Lines.Select(line => $"\"{line.Replace("\"", "\\\"")}\""))}], {input.PauseAt}, {input.PositionMode}, {input.RewindTo})";

    private static async Task<bool> WaitForAsync(Func<bool> condition)
    {
        using CancellationTokenSource cts = new(FakeFirmwareHost.DefaultTimeout);
        try
        {
            while (!condition())
            {
                await Task.Delay(5, cts.Token);
            }
            return true;
        }
        catch (OperationCanceledException)
        {
            return false;
        }
    }

    private async Task CheckJobAsync(JobInput input)
    {
        FakeFirmwareHost host = _host!;
        JobProcessor jobs = host.Services.GetRequiredService<JobProcessor>();
        string content = string.Join('\n', input.Lines) + "\n";
        System.IO.File.WriteAllText(Path.Combine(host.BaseDirectory, "gcodes", "fuzz.g"), content);

        // Byte offset of each move in the file
        long[] offsets = [.. Enumerable.Range(0, input.Lines.Count(line => line.StartsWith("G1 X")))
            .Select(i => (long)content.IndexOf($"G1 X{i}\n", StringComparison.Ordinal))];
        int executedBefore = host.Firmware.GetExecutedCodes(CodeChannel.File).Count;

        // Hold the move to pause at
        using ManualResetEventSlim release = new();
        string held = $"G1 X{input.PauseAt}";
        host.Firmware.OnCode("G1", code => (code.Text == held && !release.IsSet) ? FakeReply.NotFinished : null);
        if (await host.ExecuteAsync("M32 \"fuzz.g\"") != "\n" ||
            !await WaitForAsync(() => host.Firmware.GetExecutedCodes(CodeChannel.File).Skip(executedBefore).Any(code => code.Text == held)))
        {
            throw new FuzzFailure("start", "The job did not reach the move to pause at");
        }

        // Pause like LinkService.HandlePrintPaused does (LinkService.cs:886-904). RRF reports the position of the next code to execute,
        // and none for a pause from a code, then the job resumes after the last code it executed (JobProcessor.cs:636-641)
        long afterHeld = offsets[input.PauseAt] + held.Length + 1;
        using (await jobs.LockAsync())
        {
            jobs.Pause((input.PositionMode == 0) ? afterHeld : null, null, (input.PositionMode == 1) ? PrintPausedReason.GCode : PrintPausedReason.User);
        }
        release.Set();
        if (!await WaitForAsync(() => jobs.IsPaused && !jobs.IsProcessing))
        {
            throw new FuzzFailure("pause", "The job did not pause");
        }

        // The paused position is where the job goes on: after the held move, unless M26 sets another one (MCodeHandler.cs:286-321)
        long resumeAt = afterHeld;
        if (input.PositionMode == 2)
        {
            resumeAt = offsets[input.RewindTo];
            if (await host.ExecuteAsync($"M26 S{resumeAt}") != "\n")
            {
                throw new FuzzFailure("M26", "M26 failed while paused");
            }
        }
        string status = await host.ExecuteAsync("M27");
        string expectedStatus = $"SD printing byte {resumeAt}/{content.Length}\n";
        if (status != expectedStatus)
        {
            throw new FuzzFailure("M27", $"M27 reported '{status.TrimEnd()}' instead of '{expectedStatus.TrimEnd()}'");
        }

        if (await host.ExecuteAsync("M24") != "\n" || !await WaitForAsync(() => !jobs.IsFileSelected))
        {
            throw new FuzzFailure("resume", "The job did not finish after M24");
        }

        // The moves run up to the held one, then from the resume position to the end of the file, each with its file position
        List<FakeCode> moves = [.. host.Firmware.GetExecutedCodes(CodeChannel.File).Skip(executedBefore).Where(code => code.Text.StartsWith("G1 X"))];
        int resumeMove = Array.FindIndex(offsets, offset => offset >= resumeAt);
        IEnumerable<int> expected = Enumerable.Range(0, input.PauseAt + 1).Concat((resumeMove < 0) ? [] : Enumerable.Range(resumeMove, offsets.Length - resumeMove));
        string[] expectedMoves = [.. expected.Select(i => $"G1 X{i}")];
        if (!moves.Select(code => code.Text).SequenceEqual(expectedMoves))
        {
            throw new FuzzFailure("moves", $"Executed {string.Join(", ", moves.Select(code => code.Text))} instead of {string.Join(", ", expectedMoves)}");
        }
        foreach (FakeCode move in moves)
        {
            int number = int.Parse(move.Text["G1 X".Length..]);
            if (move.FilePosition != offsets[number])
            {
                throw new FuzzFailure("file position", $"{move.Text} came with file position {move.FilePosition} instead of {offsets[number]}");
            }
        }
    }

    [Test]
    public async Task PauseAndResumeJobs()
    {
        // One buffered print code makes JobProcessor read the next code only when the previous one has finished
        _host = await FakeFirmwareHost.StartAsync(configureSettings: settings => settings.BufferedPrintCodes = 1);
        Fuzzer.Run(GenerateJob, input => CheckJobAsync(input).GetAwaiter().GetResult(), FormatJob,
            input => (input.Lines.Count > 2) ? [input with { Lines = [.. input.Lines.Where(line => line.StartsWith("G1 X"))] }] : [],
            Fuzzer.Scale(40), TimeSpan.FromSeconds(30));
    }
    #endregion
}
