    private const int DefaultBufferSize = 32768;

    private static List<byte[]>? _corpus;

    /// <summary>
    /// Build the corpus from the seed lines and short runs of lines from the sample files
    /// </summary>
    private static List<byte[]> Corpus
    {
        get
        {
            if (_corpus is null)
            {
                List<string> entries = [.. SeedLines];
                foreach (string line in new[] { "N1 G1 X10", "N2 M117 \"a*b\"", "N3 T0", "N4" })
                {
                    entries.Add($"{line}*{DuetAPI.Commands.Code.ComputeLineChecksum(Encoding.ASCII.GetBytes(line))}");
                    entries.Add($"{line}*{DuetAPI.Commands.Code.ComputeLineCrc(Encoding.ASCII.GetBytes(line)):D5}");
                }

                foreach (string file in Directory.GetFiles(Path.Combine(Directory.GetCurrentDirectory(), "../../../File/GCodes")).Order())
                {
                    // Header lines hold the slicer metadata and thumbnails, the rest is mostly moves
                    List<string> lines = [.. System.IO.File.ReadLines(file).Take(3000)];
                    for (int i = 0; i < lines.Count; i += Math.Max(lines.Count / 40, 1))
                    {
                        entries.Add(string.Join('\n', lines.Skip(i).Take(1 + i % 4)));
                    }
                }
                _corpus = [.. entries.Distinct().Select(Encoding.UTF8.GetBytes)];
            }
            return _corpus;
        }
    }

    private static IReadOnlyList<byte[]> Dictionary => [.. Tokens.Select(Encoding.UTF8.GetBytes), .. RawTokens];

    [Test]
    public void SyncParser() => Fuzzer.Run(Corpus, input =>
    {
        // Same as FileInfoParser, which parses lines read from files with Code.Parse
        using StringReader reader = new(Encoding.UTF8.GetString(input));
        DuetAPI.Commands.Code code = new();
        try
        {
            for (int numCodes = 0; DuetAPI.Commands.Code.Parse(reader, code); numCodes++)
            {
                if (numCodes > input.Length)
                {
                    throw new FuzzFailure("progress", "Code.Parse keeps returning codes without consuming input");
                }
                _ = code.ToString();
                code.Reset();
            }
        }
        catch (CodeParserException)
        {
            // Expected for invalid codes
        }
    }, Dictionary);

    [Test]
    public void AsyncParser() => Fuzzer.Run(Corpus, CheckAsyncParser, Dictionary);

    [Test]
    public void SyncMatchesAsync() => Fuzzer.Run(Corpus, input => CheckSyncMatchesAsync(input, false), Dictionary);

    [Test]
    public void SyncMatchesAsyncOnFollowingCodes() => Fuzzer.Run(Corpus, input => CheckSyncMatchesAsync(input, true), Dictionary);

    /// <summary>
    /// Parse the first line with both parsers and compare the results
    /// </summary>
    /// <param name="input">Input to parse</param>
    /// <param name="followingCodes">Whether to compare the following codes on the line as well, or only the first one like the Code(string) constructor reads</param>
    private static void CheckSyncMatchesAsync(byte[] input, bool followingCodes)
    {
        // The sync parser is only used line by line, see FileInfoParser
        int end = Array.IndexOf(input, (byte)'\n');
        byte[] line = (end < 0) ? input : input[..end];
        if (!Utf8.IsValid(line))
        {
            // The sync parser gets decoded text, so invalid UTF-8 cannot reach it in the same form
            return;
        }

        List<string> syncResult = [];
        try
        {
            using StringReader reader = new(Encoding.UTF8.GetString(line));
            for (DuetAPI.Commands.Code code = new(); DuetAPI.Commands.Code.Parse(reader, code); code = new())
            {
                if (syncResult.Count > line.Length)
                {
                    throw new FuzzFailure("progress", "Code.Parse keeps returning codes without consuming input");
                }
                syncResult.Add(Describe(code, syncResult.Count == 0));
                if (!followingCodes)
                {
                    break;
                }
            }
        }
        catch (CodeParserException)
        {
            syncResult.Add("parse error");
        }

        // Same as the IPC code stream, which parses each line with a fresh stream and a shared buffer
        List<string> asyncResult = [];
        try
        {
            using MemoryStream stream = new(line);
            CodeParserBuffer buffer = new(DefaultBufferSize, false);
            for (DuetAPI.Commands.Code code = new(); DuetAPI.Commands.Code.ParseAsync(stream, code, buffer).AsTask().GetAwaiter().GetResult(); code = new())
            {
                if (asyncResult.Count > line.Length)
                {
                    throw new FuzzFailure("progress", "Code.ParseAsync keeps returning codes without consuming input");
                }
                asyncResult.Add(Describe(code, asyncResult.Count == 0));
                if (!followingCodes)
                {
                    break;
                }
            }
        }
        catch (CodeParserException)
        {
            asyncResult.Add("parse error");
        }

        // Only the async parser verifies the checksum or CRC of a numbered line, and the sync parser strips it only after the code holding the line number
        if (!syncResult.SequenceEqual(asyncResult) && !line.Contains((byte)'*'))
        {
            throw new FuzzFailure("sync vs async", $"Results differ:\nCode.Parse: {string.Join(" | ", syncResult)}\nCode.ParseAsync: {string.Join(" | ", asyncResult)}");
        }
    }

    /// <summary>
    /// Parse an input as a file with a large and a small buffer
    /// </summary>
    /// <param name="input">Input to parse</param>
    private static void CheckAsyncParser(byte[] input)
    {
        // A small buffer moves the buffer boundaries through the input and must not change the result.
        // Values below 4 bytes cannot hold a BOM, so they do not apply
        bool enforceLineNumbers = input.Length % 2 == 0;
        List<string> withLargeBuffer = ParseFile(input, DefaultBufferSize, enforceLineNumbers);
        List<string> withSmallBuffer = ParseFile(input, 4 + input.Length % 13, enforceLineNumbers);
        if (!withLargeBuffer.SequenceEqual(withSmallBuffer))
        {
            throw new FuzzFailure("buffer size", $"Results differ between buffer sizes:\n{DefaultBufferSize}: {string.Join(" | ", withLargeBuffer)}\n{4 + input.Length % 13}: {string.Join(" | ", withSmallBuffer)}");
        }
    }

    /// <summary>
    /// Parse a whole file the same way as CodeFile.ReadCodeAsync and check the file positions and lengths
    /// </summary>
    /// <param name="input">Content of the file</param>
    /// <param name="bufferSize">Size of the parser buffer</param>
    /// <param name="enforceLineNumbers">Whether line numbers and checksum types are enforced</param>
    /// <returns>Description of each code and the parse error that ended the file (if any)</returns>
    private static List<string> ParseFile(byte[] input, int bufferSize, bool enforceLineNumbers)
    {
        List<string> result = [];
        using MemoryStream stream = new(input);
        CodeParserBuffer buffer = new(bufferSize, true) { EnforceLineNumbers = enforceLineNumbers };
        DuetAPI.Commands.Code code = new();
        try
        {
            bool codeRead;
            do
            {
                if (result.Count > input.Length + 1)
                {
                    throw new FuzzFailure("progress", "Code.ParseAsync keeps returning without consuming input");
                }

                code.Reset();
                long before = buffer.GetPosition(stream);
                codeRead = DuetAPI.Commands.Code.ParseAsync(stream, code, buffer).AsTask().GetAwaiter().GetResult();
                long after = buffer.GetPosition(stream);

                // JobProcessor takes FilePosition + Length as the position after a code, so both must match what was read.
                // Before the first read the BOM check fills the buffer, so the position of an empty buffer does not apply
                if (before != 0 && code.FilePosition != before)
                {
                    throw new FuzzFailure("file position", $"FilePosition is {code.FilePosition} but the code started at {before}");
                }
                if (code.FilePosition + code.Length != after)
                {
                    throw new FuzzFailure("length", $"FilePosition {code.FilePosition} + Length {code.Length} does not match the position {after} after the code");
                }

                result.Add(codeRead ? Describe(code) : "(nothing)");
            }
            while (codeRead || buffer.GetPosition(stream) < stream.Length);
        }
        catch (CodeParserException)
        {
            result.Add("parse error");
        }
        catch (ArgumentException e) when (result.Count == 0 && e.Message.StartsWith("Cannot parse codes from UTF-"))
        {
            // Files must be ASCII or UTF-8
            result.Add("BOM error");
        }
        return result;
    }

    /// <summary>
    /// Describe everything the parser sets on a code, except for the file position
    /// </summary>
    /// <param name="code">Code to describe</param>
    /// <param name="firstOnLine">Whether this is the first code on its line. If not, leave out the line number, indentation and G53 flag,
    /// which only the async parser carries over to the following codes (see the remarks of Code.Parse)</param>
    private static string Describe(DuetAPI.Commands.Code code, bool firstOnLine = true)
    {
        CodeFlags flags = firstOnLine ? code.Flags : code.Flags & ~(CodeFlags.EnforceAbsolutePosition | CodeFlags.HasExplicitLineNumber);
        StringBuilder builder = new();
        builder.Append($"type={code.Type} major={code.MajorNumber} minor={code.MinorNumber} keyword={code.Keyword} arg={code.KeywordArgument} ");
        builder.Append($"comment={code.Comment} flags={flags} length={code.Length}");
        if (firstOnLine)
        {
            builder.Append($" indent={code.Indent} line={code.LineNumber}");
        }
        foreach (CodeParameter parameter in code.Parameters)
        {
            builder.Append($" [{parameter.Letter} '{parameter}' {parameter.Type?.Name} expr={parameter.IsExpression} driver={parameter.IsDriverId}]");
        }
        _ = code.ToString();
        return builder.ToString();
    }
