using System;
using System.IO;
using System.Text;
using System.Threading.Tasks;
using DuetAPI.ObjectModel;
using DuetControlServer.Files;
using NUnit.Framework;
using Host = UnitTests.SPI.LinkServiceOverSpi.Host;
using SbcRequest = DuetControlServer.Link.Protocol.SbcRequests.Request;

namespace UnitTests.SPI;

/// <summary>
/// The SetPrintFileInfo request for a selected job file on the real SPI adapter. SPI.WritePrintFileInfo serialises the information with
/// Writer.WritePrintFileInfo into a span of the transfer buffer (SPI.cs:1039-1061) on the link task (LinkService.cs:404-411), which has no
/// catch around it. An exception there ends the link task, and DCS stops (BackgroundServiceExceptionBehavior.StopHost)
/// </summary>
[TestFixture]
public class PrintFileInfoOverSpi
{
    private static readonly TimeSpan Timeout = LinkServiceOverSpi.Timeout;

    /// <summary>
    /// Select a job file as M32 does (MCodeHandler.cs:270-278) and wait until the link task has sent its information or stopped
    /// </summary>
    private static async Task SelectAsync(Host host, string fileName, string content)
    {
        string physicalFile = Path.Combine(host.BaseDirectory, "gcodes", fileName);
        System.IO.File.WriteAllText(physicalFile, content);

        JobProcessor jobs = host.Get<JobProcessor>();
        Task fileInfoSent;
        using (await jobs.LockAsync())
        {
            fileInfoSent = await jobs.SelectFileAsync("0:/gcodes/" + fileName, physicalFile);
        }
        await Task.WhenAny(fileInfoSent, host.Service.ExecuteTask!).WaitAsync(Timeout);
    }

    /// <summary>
    /// Number of filaments in a SetPrintFileInfo packet (PrintStartedHeader.NumFilaments)
    /// </summary>
    private static uint NumFilaments(byte[] packet) => BitConverter.ToUInt32(packet, 4);

    /// <summary>
    /// File name of a SetPrintFileInfo packet, which follows the 40-byte header and the filaments
    /// </summary>
    private static string FileName(byte[] packet) => Encoding.UTF8.GetString(packet, 40 + 4 * (int)NumFilaments(packet), BitConverter.ToUInt16(packet, 0));

    /// <summary>
    /// Slicer of a SetPrintFileInfo packet, which follows the file name
    /// </summary>
    private static string GeneratedBy(byte[] packet) =>
        Encoding.UTF8.GetString(packet, 40 + 4 * (int)NumFilaments(packet) + BitConverter.ToUInt16(packet, 0), BitConverter.ToUInt16(packet, 2));

    /// <summary>
    /// A filament index from a comment made FileInfoParser add that many filaments, and 40 + 4 * 2101 bytes do not fit into the 8184 bytes of the
    /// packet span, so the Writer threw ArgumentOutOfRangeException on the link task
    /// </summary>
    [Test]
    public async Task FilamentIndexDoesNotStopTheLink()
    {
        await using Host host = await Host.StartAsync();
        await SelectAsync(host, "job.g", ";Material#0 Used: 5.0\n;Material#2100 Used: 1.0\nG1 X1\n");
        Assert.That(host.Fault, Is.Null);
        Assert.That(NumFilaments(host.WaitFor(SbcRequest.SetPrintFileInfo)), Is.EqualTo(1));
    }

    /// <summary>
    /// The file name in the request may have 254 UTF-8 bytes (Writer.WritePrintFileInfo). A longer one made the Writer throw ArgumentException on
    /// the link task. Linux allows 255 bytes per name, so the virtual path of a file in 0:/gcodes/ can have up to 265 bytes, here 255 with 93
    /// characters. RRF holds 120 bytes of the path (MaxFilenameLength, Configuration.h:143) and cuts a longer one, which a path of 121 bytes in
    /// 49 characters already exceeds
    /// </summary>
    [TestCase(81, ".g"), TestCase(36, "a.g")]
    public async Task LongFileNameIsRefusedBeforeTheLink(int euros, string suffix)
    {
        await using Host host = await Host.StartAsync();
        Assert.That(async () => await SelectAsync(host, new string('\u20AC', euros) + suffix, "G1 X1\n"), Throws.ArgumentException);
        Assert.That(host.Get<JobProcessor>().IsFileSelected, Is.False);

        // The link carries on
        await SelectAsync(host, "job.g", "G1 X1\n");
        Assert.That(host.Fault, Is.Null);
        Assert.That(FileName(host.WaitFor(SbcRequest.SetPrintFileInfo)), Is.EqualTo("0:/gcodes/job.g"));
    }

    /// <summary>
    /// FileInfoParser takes the slicer from a comment without a limit (FileInfoParser.cs:582-594), and one of more than 254 UTF-8 bytes made the
    /// Writer throw ArgumentException on the link task. RRF keeps 50 bytes of it (GCodeFileInfo.h:46), so the Writer cuts it like a comment
    /// (Writer.cs:141-153), on a UTF-8 character boundary
    /// </summary>
    [Test]
    public async Task LongSlicerIsCut()
    {
        await using Host host = await Host.StartAsync();
        await SelectAsync(host, "job.g", "; generated by " + new string('x', 300) + "\nG1 X1\n");
        Assert.That(host.Fault, Is.Null);
        Assert.That(GeneratedBy(host.WaitFor(SbcRequest.SetPrintFileInfo)), Is.EqualTo(new string('x', 254)));

        // The object model keeps the whole slicer
        using (await host.Model.AccessReadOnlyAsync())
        {
            Assert.That(host.Model.Job.File.GeneratedBy, Has.Length.EqualTo(300));
        }

        await host.Link.SetPrintFileInfo(new GCodeFileInfo { FileName = "0:/gcodes/job.g", GeneratedBy = new string('\u20AC', 100) }).Unwrap().WaitAsync(Timeout);
        Assert.That(host.Fault, Is.Null);
        Assert.That(GeneratedBy(host.WaitFor(SbcRequest.SetPrintFileInfo)), Is.EqualTo(new string('\u20AC', 84)));
    }
}
