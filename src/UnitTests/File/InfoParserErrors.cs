using System.IO;
using System.Threading.Tasks;
using DuetAPI;
using DuetAPI.ObjectModel;
using DuetControlServer.Files.Parser;
using Microsoft.Extensions.DependencyInjection;
using NUnit.Framework;
using UnitTests.FakeFirmware;

namespace UnitTests.File;

/// <summary>
/// G-code files with a line that the code parser rejects, found by GCodeFileFuzz.ParseFileInfo. FileInfoParser parses the header and the
/// footer with the code parser (FileInfoParser.cs:149 and 205) and passes on its CodeParserException, which fails M36 and also M32,
/// because JobProcessor.SelectFileAsync needs the file information (JobProcessor.cs:311). The same goes for the InvalidParameterTypeException
/// of a G0/G1 Z parameter without a number in the footer (FileInfoParser.cs:221, Code.TryGetFloat)
/// </summary>
[TestFixture]
public class InfoParserErrors
{
    private FakeFirmwareHost _host = null!;

    [SetUp]
    public async Task SetUp() => _host = await FakeFirmwareHost.StartAsync();

    [TearDown]
    public async Task TearDown() => await _host.DisposeAsync();

    private string WriteJob(string content)
    {
        string path = Path.Combine(_host.BaseDirectory, "gcodes", "job.gcode");
        System.IO.File.WriteAllText(path, content);
        return path;
    }

    [TestCase("G1 X1\nM117 \"unterminated\n")]
    [TestCase("G1 X1\n0.5 E2\n")]
    [TestCase("; generated by PrusaSlicer 2.6.0\nG1 X1 Y\"a\n")]
    [TestCase("G1 X1\nG1 Z\n")]
    [TestCase("G1 X1\nG1 Z\"a\"\n")]
    [Explicit("A line that the code parser rejects in the header or the footer makes FileInfoParser.ParseAsync throw instead of returning the information it found, so the file cannot be printed")]
    public async Task MalformedLine(string content)
    {
        // RRF's FileInfoParser scans the text for key phrases (FileInfoParser.cpp:425-455) and catches the exceptions of the expressions it evaluates
        // (FileInfoParser.cpp:911-918), so a malformed line does not stop it. A truncated upload ends with such a line, too
        string path = WriteJob(content);
        GCodeFileInfo info = await _host.Services.GetRequiredService<FileInfoParser>().ParseAsync(path, false);
        Assert.That(info.Size, Is.EqualTo(new FileInfo(path).Length));
        Assert.That(await _host.ExecuteAsync("M32 \"job.gcode\""), Is.EqualTo("\n"));
    }

    [Test]
    public async Task WellFormedFile()
    {
        string path = WriteJob("; generated by PrusaSlicer 2.6.0\nG1 X1 Z0.3\n");
        GCodeFileInfo info = await _host.Services.GetRequiredService<FileInfoParser>().ParseAsync(path, false);
        Assert.That(info.GeneratedBy, Is.EqualTo("PrusaSlicer 2.6.0"));
        Assert.That(info.FileName, Is.EqualTo("0:/gcodes/job.gcode"));
    }
}
